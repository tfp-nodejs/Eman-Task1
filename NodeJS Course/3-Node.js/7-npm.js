// What Is npm?

// - Stands for Node Package Manager
// - Default package manager for Node.js
// - Comes installed with Node.js
// - Lets you install, manage, and share reusable code modules

// https://www.npmjs.com/

// Installing Packages (Locally)

// npm install package-name
// or shorthand:
// npm i package-name;

// Example:
// npm i lodash;

// Installed packages go inside node_modules folder and listed in package.json under "dependencies"

// Global Packages

// Installed globally (available everywhere on your system)
// npm install -g package-name

// Example:
// npm i -g nodemon

// To uninstall global packages
// npm uninstall -g package-name

// Example:
// npm uninstall -g nodemon

// What is npx?

// npx allows you to run a package without installing it globally
// Example:
// npx create-react-app myApp

// Runs create-react-app immediately, then removes it

// Great for one-time tools

// Initialize a New Project

// npm init        → step-by-step prompts
// npm init -y     → create package.json with default values

// What is package.json?

// A file generated by npm init that holds project info and dependencies

/* Example package.json:

{
  "name": "my-project",               // Project name
  "version": "1.0.0",                 // Project version (SemVer format)
  "description": "A demo project",    // Description
  "main": "index.js",                 // Entry point file
  "scripts": {                        // Custom terminal commands (npm run <script>)
    "start": "node index.js",
  },
  "author": "Your Name",              // Author info
  "dependencies": {},                 // Installed packages
  "devDependencies": {}               // Development-only packages
}

*/

// node_modules Folder

// - Created when installing packages
// - Contains all installed packages + their dependencies
// - Should be ignored from Git using .gitignore

// package-lock.json

// - Auto-generated when installing packages
// - Locks exact versions of dependencies for consistency across machines
// - Keeps track of dependency tree and version numbers

// Semantic Versioning (SemVer)

// version: MAJOR.MINOR.PATCH

// Example: "lodash": "^4.17.21"

// 4 → MAJOR → Breaking changes
// 17 → MINOR → New features
// 21 → PATCH → Bug fixes
