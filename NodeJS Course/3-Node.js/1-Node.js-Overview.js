//  What is Node.js?

// - Node.js is a JavaScript runtime environment built on Chrome's V8 JavaScript engine.
// - It allows you to run JavaScript outside the browser, typically on servers.
// - Uses Google’s V8 engine (the same engine that powers Chrome) to execute JavaScript code.

//  Quick History:
// - Created by Ryan Dahl in 2009 using Chrome’s V8 JavaScript engine.
// - Designed to handle asynchronous, event-driven, non-blocking I/O operations, making it ideal for building scalable network applications like APIs and real-time apps (e.g., chat apps, streaming services).

//  Why Use Node.js?

// - Fast execution thanks to V8.
// - Non-blocking I/O means it can handle many requests simultaneously without waiting for one to finish before starting another.
// - Event-driven architecture is perfect for applications that require high concurrency.
// - Single language on both client and server: JavaScript everywhere!
// - Huge ecosystem via npm (Node Package Manager).

//  Summary:

// - Node.js enables JavaScript to run on servers.
// - It's perfect for building scalable APIs and real-time apps.
// - Powered by V8, created by Ryan Dahl in 2009.
