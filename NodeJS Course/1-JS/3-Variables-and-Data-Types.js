// Variables and Data Types

// - Variables are containers for storing data values. In JavaScript, we declare them using var, let, or const.

// - Data types include: Number, String, Boolean, Object, Array, Null, and Undefined.

// - 'let' allows reassignment but not redeclaration within the same scope.

// - 'const' cannot be reassigned or redeclared — it's a constant reference.

// // Example 1: Redeclaring with var
// var a = 5;
// var a = 10;
// console.log(a);

// // Example 2: Access Before Declaration (Hoisting)
// console.log(b);
// var b = 10;

// // Example 3: Reassignment and Constants
